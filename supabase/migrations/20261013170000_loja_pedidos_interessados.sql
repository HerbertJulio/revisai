-- Revisaí: loja (fornecedores, produtos e promoções), pedidos das oficinas e cadastro de interessados.
-- O público só lê o catálogo ativo. Pedidos e interessados só recebem inserções; quem lê é a equipe,
-- pelo painel do Supabase.

-- Tabelas e funções novas não ficam abertas para a API: cada papel recebe só o que precisa.
alter default privileges for role postgres in schema public revoke all on tables from anon, authenticated;
alter default privileges for role postgres in schema public revoke all on sequences from anon, authenticated;
alter default privileges for role postgres in schema public revoke execute on functions from public, anon, authenticated;

create table public.fornecedores (
  id bigint generated by default as identity primary key,
  nome text not null check (char_length(nome) between 2 and 120),
  cidade text check (char_length(cidade) <= 80),
  uf text check (uf ~ '^[A-Z]{2}$'),
  whatsapp text check (whatsapp ~ '^55[0-9]{10,11}$'),
  demonstracao boolean not null default false,
  ativo boolean not null default true,
  criado_em timestamptz not null default now()
);

comment on table public.fornecedores is 'Quem vende na loja. demonstracao = dados de exemplo.';

create table public.produtos (
  id bigint generated by default as identity primary key,
  fornecedor_id bigint not null references public.fornecedores (id),
  categoria text not null check (categoria in (
    'oleo_motor', 'filtro_oleo', 'filtro_ar', 'filtro_cabine', 'filtro_combustivel', 'vela',
    'correia_dentada', 'correia_acessorios', 'pastilha_freio', 'disco_freio', 'fluido_freio',
    'arrefecimento', 'pneu', 'bateria', 'amortecedor', 'fluido_cambio', 'higienizacao_ar', 'palheta', 'outros'
  )),
  nome text not null check (char_length(nome) between 2 and 160),
  marca text check (char_length(marca) <= 80),
  descricao text check (char_length(descricao) <= 600),
  unidade text not null default 'un' check (unidade in ('un', 'L', 'kit', 'par', 'jogo')),
  conteudo numeric(8, 2) check (conteudo > 0),
  preco numeric(10, 2) not null check (preco > 0),
  especificacao jsonb not null default '{}'::jsonb check (jsonb_typeof(especificacao) = 'object'),
  intervalo_km integer check (intervalo_km between 1 and 300000),
  intervalo_meses integer check (intervalo_meses between 1 and 180),
  ativo boolean not null default true,
  criado_em timestamptz not null default now()
);

comment on column public.produtos.conteudo is 'Litros por unidade (óleo e fluidos) ou litros do kit.';
comment on column public.produtos.especificacao is 'viscosidade, base, api, ilsac, acea[], normas[], medida, amperagem, tipo.';
comment on column public.produtos.intervalo_km is 'Vida útil ou limite de troca do produto (ex.: óleo mineral 5000).';

create index produtos_fornecedor_id_idx on public.produtos (fornecedor_id);

create table public.promocoes (
  id bigint generated by default as identity primary key,
  produto_id bigint not null references public.produtos (id) on delete cascade,
  titulo text not null check (char_length(titulo) between 2 and 80),
  preco_promocional numeric(10, 2) not null check (preco_promocional > 0),
  quantidade_minima integer not null default 1 check (quantidade_minima between 1 and 1000),
  inicio date not null default current_date,
  fim date not null,
  ativo boolean not null default true,
  criado_em timestamptz not null default now(),
  constraint promocoes_periodo check (fim >= inicio)
);

create index promocoes_produto_id_idx on public.promocoes (produto_id);

create table public.pedidos (
  id bigint generated always as identity primary key,
  codigo text not null unique check (codigo ~ '^[A-Z0-9]{6}$'),
  oficina_nome text not null check (char_length(oficina_nome) between 2 and 120),
  oficina_whatsapp text not null check (oficina_whatsapp ~ '^55[0-9]{10,11}$'),
  oficina_cidade text check (char_length(oficina_cidade) <= 80),
  oficina_uf text check (oficina_uf ~ '^[A-Z]{2}$'),
  itens jsonb not null check (jsonb_typeof(itens) = 'array' and jsonb_array_length(itens) between 1 and 50),
  total numeric(12, 2) not null default 0 check (total >= 0),
  observacao text check (char_length(observacao) <= 500),
  status text not null default 'novo' check (status in ('novo', 'em_contato', 'confirmado', 'entregue', 'cancelado')),
  criado_em timestamptz not null default now()
);

comment on table public.pedidos is 'Pedidos enviados pelas oficinas na loja. Preços e total são recalculados pelo banco.';

create table public.interessados (
  id bigint generated always as identity primary key,
  tipo text not null check (tipo in ('oficina', 'fornecedor', 'motorista', 'contato')),
  nome text not null check (char_length(nome) between 2 and 120),
  empresa text check (char_length(empresa) <= 120),
  whatsapp text check (whatsapp ~ '^55[0-9]{10,11}$'),
  email text check (char_length(email) <= 160 and email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
  cidade text check (char_length(cidade) <= 80),
  uf text check (uf ~ '^[A-Z]{2}$'),
  plano text check (plano in ('gratis', 'plus', 'vitrine', 'destaque', 'oferta')),
  mensagem text check (char_length(mensagem) <= 1000),
  origem text check (char_length(origem) <= 60),
  consentimento boolean not null default false,
  criado_em timestamptz not null default now(),
  constraint interessados_contato check (whatsapp is not null or email is not null)
);

comment on table public.interessados is 'Oficinas querendo o Plus, fornecedores querendo anunciar, donos de carro e contatos.';

-- O banco confere cada produto e recalcula preço, promoção e total: o navegador não manda preço.
create or replace function public.calcular_pedido()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_item jsonb;
  v_calculados jsonb := '[]'::jsonb;
  v_produto_id bigint;
  v_quantidade integer;
  v_nome text;
  v_preco numeric(10, 2);
  v_fornecedor_id bigint;
  v_fornecedor text;
  v_promocional numeric(10, 2);
  v_unitario numeric(10, 2);
  v_soma numeric(12, 2) := 0;
  v_hoje date := (now() at time zone 'America/Sao_Paulo')::date;
begin
  for v_item in select value from jsonb_array_elements(new.itens)
  loop
    if jsonb_typeof(v_item -> 'produto_id') is distinct from 'number'
       or jsonb_typeof(v_item -> 'quantidade') is distinct from 'number' then
      raise exception 'Item de pedido inválido' using errcode = '22023';
    end if;
    v_produto_id := (v_item ->> 'produto_id')::bigint;
    v_quantidade := (v_item ->> 'quantidade')::integer;
    if v_quantidade < 1 or v_quantidade > 999 then
      raise exception 'Quantidade inválida' using errcode = '22023';
    end if;

    select p.nome, p.preco, p.fornecedor_id, f.nome
      into v_nome, v_preco, v_fornecedor_id, v_fornecedor
      from public.produtos p
      join public.fornecedores f on f.id = p.fornecedor_id
     where p.id = v_produto_id and p.ativo and f.ativo;
    if not found then
      raise exception 'Produto % indisponível', v_produto_id using errcode = '22023';
    end if;

    select min(pr.preco_promocional) into v_promocional
      from public.promocoes pr
     where pr.produto_id = v_produto_id
       and pr.ativo
       and v_hoje between pr.inicio and pr.fim
       and v_quantidade >= pr.quantidade_minima;

    v_unitario := least(v_preco, coalesce(v_promocional, v_preco));
    v_soma := v_soma + v_unitario * v_quantidade;
    v_calculados := v_calculados || jsonb_build_array(jsonb_build_object(
      'produto_id', v_produto_id,
      'nome', v_nome,
      'fornecedor_id', v_fornecedor_id,
      'fornecedor', v_fornecedor,
      'quantidade', v_quantidade,
      'preco_unitario', v_unitario,
      'promocao', coalesce(v_promocional < v_preco, false)
    ));
  end loop;

  new.itens := v_calculados;
  new.total := v_soma;
  new.status := 'novo';
  new.criado_em := now();
  return new;
end;
$$;

revoke all on function public.calcular_pedido() from public, anon, authenticated;

create trigger pedidos_calcular
before insert on public.pedidos
for each row execute function public.calcular_pedido();

alter table public.fornecedores enable row level security;
alter table public.produtos enable row level security;
alter table public.promocoes enable row level security;
alter table public.pedidos enable row level security;
alter table public.interessados enable row level security;

create policy "Catálogo: fornecedores ativos" on public.fornecedores
  for select to anon, authenticated using (ativo);

create policy "Catálogo: produtos ativos" on public.produtos
  for select to anon, authenticated using (ativo);

create policy "Catálogo: promoções em vigor" on public.promocoes
  for select to anon, authenticated using (ativo and fim >= (now() at time zone 'America/Sao_Paulo')::date);

create policy "Oficinas enviam pedidos" on public.pedidos
  for insert to anon, authenticated with check (status = 'novo' and total >= 0);

create policy "Interessados se cadastram com consentimento" on public.interessados
  for insert to anon, authenticated with check (consentimento);

grant select on public.fornecedores, public.produtos, public.promocoes to anon, authenticated;
grant insert on public.pedidos, public.interessados to anon, authenticated;
